/**
 * Format bytes into readable string (KB, MB, GB)
 */
export function formatBytes(bytes: number, decimals: number = 1): string {
  if (bytes <= 0) return '0 B';
  const k = 1024;
  const dm = decimals < 0 ? 0 : decimals;
  const sizes = ['B', 'KB', 'MB', 'GB', 'TB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return `${parseFloat((bytes / Math.pow(k, i)).toFixed(dm))} ${sizes[i]}`;
}

/**
 * Parse BeamMP ServerConfig.toml
 */
export function parseServerConfigToml(tomlStr: string): Partial<ServerConfigToml> {
  const result: Partial<ServerConfigToml> = {};
  const lines = tomlStr.split('\n');

  let currentSection = '';

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;

    if (line.startsWith('[') && line.endsWith(']')) {
      currentSection = line.substring(1, line.length - 1).trim();
      continue;
    }

    const eqIdx = line.indexOf('=');
    if (eqIdx !== -1) {
      const key = line.substring(0, eqIdx).trim();
      let value = line.substring(eqIdx + 1).trim();

      // Remove inline comments
      const commentIdx = value.indexOf('#');
      if (commentIdx !== -1 && !value.startsWith('"')) {
        value = value.substring(0, commentIdx).trim();
      }

      // Parse string
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
        const strVal = value.substring(1, value.length - 1);
        (result as Record<string, unknown>)[key] = strVal;
      } else if (value.toLowerCase() === 'true') {
        (result as Record<string, unknown>)[key] = true;
      } else if (value.toLowerCase() === 'false') {
        (result as Record<string, unknown>)[key] = false;
      } else if (!isNaN(Number(value))) {
        (result as Record<string, unknown>)[key] = Number(value);
      } else {
        (result as Record<string, unknown>)[key] = value;
      }
    }
  }

  return result;
}

/**
 * Serialize ServerConfigToml to standard BeamMP format
 */
export function serializeServerConfigToml(config: ServerConfigToml): string {
  return `# BeamMP Server Configuration
# Generated by BeamDeck MP Server Manager
# Visit https://beammp.com for documentation

[General]
Name = "${config.Name.replace(/"/g, '\\"')}"
Description = "${config.Description.replace(/"/g, '\\"')}"
Map = "${config.Map}"
MaxPlayers = ${Math.max(1, config.MaxPlayers || 8)}
MaxCars = ${Math.max(1, config.MaxCars || 1)}
Port = ${config.Port || 30814}
AuthKey = "${config.AuthKey || ''}"
Private = ${config.Private ? 'true' : 'false'}
Debug = ${config.Debug ? 'true' : 'false'}
LogChat = ${config.LogChat ? 'true' : 'false'}
ResourceFolder = "${config.ResourceFolder || 'Resources'}"
TickRate = ${config.TickRate || 60}
`;
}

/**
 * Validate and categorize uploaded mod file for BeamMP
 */
export function validateModFile(
  filename: string,
  sizeBytes: number
): {
  valid: boolean;
  category: ModCategory;
  name: string;
  error?: string;
} {
  const cleanName = filename.trim();
  const lower = cleanName.toLowerCase();

  if (!cleanName) {
    return { valid: false, category: 'vehicle', name: '', error: 'Filename cannot be empty.' };
  }

  // BeamMP mods are almost always .zip archives for client resources or .lua for server scripts
  const isZip = lower.endsWith('.zip');
  const isLua = lower.endsWith('.lua');

  if (!isZip && !isLua) {
    return {
      valid: false,
      category: 'vehicle',
      name: cleanName,
      error: 'BeamMP mods must be .zip client resources or .lua server scripts.'
    };
  }

  if (sizeBytes > 750 * 1024 * 1024) {
    return {
      valid: false,
      category: 'vehicle',
      name: cleanName,
      error: 'Mod exceeds maximum recommended size of 750MB. Large mods cause client timeout upon joining.'
    };
  }

  // Detect category from naming patterns
  let category: ModCategory = 'vehicle';
  const baseName = cleanName.replace(/\.(zip|lua)$/i, '');

  if (isLua) {
    category = 'plugin';
  } else if (
    lower.includes('map') ||
    lower.includes('track') ||
    lower.includes('island') ||
    lower.includes('city') ||
    lower.includes('circuit') ||
    lower.includes('drift_') ||
    lower.includes('highway')
  ) {
    category = 'map';
  } else if (lower.includes('plugin') || lower.includes('server') || lower.includes('cobalt')) {
    category = 'plugin';
  } else if (lower.includes('ui') || lower.includes('app') || lower.includes('hud')) {
    category = 'ui';
  } else if (lower.includes('script') || lower.includes('tcs') || lower.includes('teleport')) {
    category = 'script';
  } else {
    // Default vehicle or vehicle accessory
    category = 'vehicle';
  }

  // Clean formatted name
  const formattedName = baseName
    .replace(/[_-]/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase());

  return {
    valid: true,
    category,
    name: formattedName
  };
}

/**
 * Generate intelligent performance recommendations based on host environment
 */
export function analyzeHostPerformance(params: {
  cpuTotalPercent: number;
  ramUsedPercent: number;
  playerCount: number;
  activeModsCount: number;
  isLocalHost: boolean;
  tickRate: number;
  highPhysicsCoreUsage?: boolean;
}): string[] {
  const recommendations: string[] = [];

  if (params.isLocalHost) {
    recommendations.push(
      'Local PC Host Mode: Since BeamNG client and server run on this machine, reserve at least 4 CPU threads exclusively for game physics.'
    );

    if (params.cpuTotalPercent > 80) {
      recommendations.push(
        'Critical CPU Load: Local PC is under heavy contention. Lower MaxCars to 1 per player to prevent client frame drops.'
      );
    }

    if (params.ramUsedPercent > 85) {
      recommendations.push(
        'High RAM Allocation: Close background browsers or heavy applications to prevent Windows paging file stutter.'
      );
    }
  } else {
    recommendations.push(
      'Dedicated Server Mode: Server process is isolated. Tick stability is high; can safely support higher vehicle limits.'
    );

    if (params.cpuTotalPercent > 75) {
      recommendations.push(
        'Server CPU Saturation: Consider enabling tick-rate throttling or decreasing player slots during peak hours.'
      );
    }
  }

  if (params.highPhysicsCoreUsage) {
    recommendations.push(
      'Core 0/1 Physics Spike: One or more modded vehicles have complex jbeam soft-body meshes. Inspect recently added mods.'
    );
  }

  if (params.activeModsCount > 15) {
    recommendations.push(
      'High Mod Count: 15+ active mods increase client join sync time. Disable unused vehicle mods to reduce bandwidth.'
    );
  }

  if (params.tickRate < 55) {
    recommendations.push(
      `Tickrate Warning: Server running at ${params.tickRate.toFixed(1)} Hz (target 60 Hz). Check network jitter or CPU thermal throttling.`
    );
  } else {
    recommendations.push('Tickrate Optimal: Synchronized physics simulation running at solid target frequency.');
  }

  return recommendations;
}

/**
 * Evaluate player permission against role configuration
 */
export function checkPermission(
  rolePermissions: RolePermissions,
  action: 'console' | 'upload_mod' | 'delete_mod' | 'edit_config' | 'kick_ban' | 'teleport' | 'slow_motion'
): boolean {
  switch (action) {
    case 'console':
      return rolePermissions.canAccessConsole;
    case 'upload_mod':
      return rolePermissions.canUploadMods;
    case 'delete_mod':
      return rolePermissions.canDeleteMods;
    case 'edit_config':
      return rolePermissions.canEditConfig;
    case 'kick_ban':
      return rolePermissions.canKickBan;
    case 'teleport':
      return rolePermissions.canTeleport;
    case 'slow_motion':
      return rolePermissions.canSlowMotion;
    default:
      return false;
  }
}

/**
 * Calculate next backup run date from schedule
 */
export function calculateNextBackupRun(schedule: BackupScheduleConfig, referenceDate: Date = new Date()): Date {
  const next = new Date(referenceDate);
  const [hours, minutes] = (schedule.timeOfDay || '04:00').split(':').map(Number);

  if (schedule.frequency === 'hourly') {
    next.setHours(next.getHours() + 1, 0, 0, 0);
  } else if (schedule.frequency === 'daily') {
    next.setHours(hours, minutes, 0, 0);
    if (next <= referenceDate) {
      next.setDate(next.getDate() + 1);
    }
  } else if (schedule.frequency === 'weekly') {
    next.setHours(hours, minutes, 0, 0);
    // Move to next Sunday
    const daysUntilSunday = (7 - next.getDay()) % 7;
    next.setDate(next.getDate() + (daysUntilSunday === 0 ? 7 : daysUntilSunday));
  }

  return next;
}

/**
 * Generate cross-platform server startup & maintenance scripts
 */
export function generateOsStartupScript(
  os: OperatingSystem,
  serverPath: string,
  port: number
): { filename: string; content: string; instructions: string } {
  switch (os) {
    case 'windows':
      return {
        filename: 'run_beammp_server.bat',
        content: `@echo off
title BeamMP Server - BeamDeck Managed
cd /d "${serverPath}"
echo [BeamDeck] Starting BeamMP Server on Port ${port}...
echo [BeamDeck] Ensuring firewall UDP/TCP port ${port} is opened...
netsh advfirewall firewall add rule name="BeamMP Server ${port}" dir=in action=allow protocol=UDP localport=${port} >nul 2>&1
netsh advfirewall firewall add rule name="BeamMP Server ${port} TCP" dir=in action=allow protocol=TCP localport=${port} >nul 2>&1
:loop
echo [BeamDeck] Launching BeamMPServer.exe...
BeamMPServer.exe
echo [BeamDeck] Server exited. Restarting in 5 seconds... (Ctrl+C to abort)
timeout /t 5
goto loop
`,
        instructions: `Save this script into "${serverPath}" and run as Administrator to automatically open firewall rules and keep the server running with auto-restart.`
      };

    case 'linux':
      return {
        filename: 'beammp.service',
        content: `[Unit]
Description=BeamMP Dedicated Server
After=network.target

[Service]
Type=simple
User=root
WorkingDirectory=${serverPath}
ExecStart=${serverPath}/BeamMP-Server
Restart=always
RestartSec=5
LimitNOFILE=65535

[Install]
WantedBy=multi-user.target
`,
        instructions: `Place this file in "/etc/systemd/system/beammp.service" and run:\nsudo systemctl daemon-reload\nsudo systemctl enable --now beammp\nsudo ufw allow ${port}/udp\nsudo ufw allow ${port}/tcp`
      };

    case 'macos':
      return {
        filename: 'start_beammp.command',
        content: `#!/bin/bash
cd "${serverPath}"
echo "[BeamDeck] Starting BeamMP Server on macOS..."
chmod +x ./BeamMP-Server
while true; do
  ./BeamMP-Server
  echo "[BeamDeck] Server stopped. Restarting in 5 seconds..."
  sleep 5
done
`,
        instructions: `Save as start_beammp.command in "${serverPath}", run "chmod +x start_beammp.command", and double-click to launch in Terminal.`
      };
  }
}
